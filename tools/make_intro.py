"""New-game intro cutscene art. The mother is built with the same pixel-art enemy pipeline (tools/build_enemy_sheets.py -> Aseprite export);
the supermarket backdrop is drawn by tools/ase/intro_bg.lua. Everything is embedded in js/introArt.js (INTRO_SHEETS / INTRO_BG), used by js/intro.js.
usage: python tools/make_intro.py [mom] [bg] [--preview]"""
import base64, io, json, os, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASEPRITE = r'F:\Dev\Tooling\aseprite\build\bin\aseprite.exe'
OUT = os.path.join(ROOT, 'assets', 'intro'); os.makedirs(OUT, exist_ok=True)
fw = lambda p: p.replace(chr(92), '/')
args = [a for a in sys.argv[1:] if not a.startswith('--')]

MOM = dict(key='intro_mom', kind='grunt', level=1, skin='#e8b894', head='blonde', hat='#c9a0ff', hair='#c9a0ff', accent='#ff8adf',
           top='jacket', jacket='#7fe3c8', sleeve='#7fe3c8', tee0='#ffffff', tee1='#ff8adf', pants='#4a78c8', trim='#ffffff', shoe='#ffffff', wrap='#ffffff', sleeves='short')

def mom_plan(sp):
    """civilian poses: arms down, feet together; talk = a wagging hand; arms_up = outrage"""
    import math, make_enemy_sprites as M
    P = M.POSES; st = dict(P['stance']); st.update(lean=0.0, hFx=3.0, hFy=27.0, hBx=-3.0, hBy=26.0, fFx=2.5, fBx=-2.5, hy=25.0)
    fr = []
    for i, b in enumerate([1, -1]): fr.append(('stand%d' % i, M.idle_pose(b, 0, st), (0, b)))
    tk = dict(st); tk.update(hFx=17.0, hFy=48.0, lean=0.06)
    for i, b in enumerate([1, -1]): fr.append(('talk%d' % i, M.idle_pose(b, b * 2, tk), (1, b)))
    for i in range(6): fr.append(('walk%d' % i, M.walk_pose(i * 2 * math.pi / 6, st, 0.8), (-1, 1.2 * abs(math.cos(i * math.pi / 3)))))
    fr += [('hurt', P['hurt'], (3, 0)), ('hurt2', P['hurt2'], (4, 1)), ('tumble', P['tumble'], (3, 3)), ('down', P['down'], (0, 0)),
           ('getup0', M.lerp_pose(P['down'], P['getup'], .5), (0, 0)), ('getup1', P['getup'], (-1, 0)), ('arms_up', P['arms_up'], (0, 4))]
    return fr

def build_mom():
    import build_enemy_sheets as B
    B.frame_plan = mom_plan
    key, b64, data, n = B.build_one(MOM)
    for ext in ('aseprite', 'json', 'png'):   # build_one drops its working files in assets/enemies: not wanted there
        f = os.path.join(ROOT, 'assets', 'enemies', 'intro_mom.' + ext)
        if os.path.exists(f): os.remove(f)
    png = os.path.join(OUT, 'mom.png'); open(png, 'wb').write(base64.b64decode(b64)); json.dump(data, open(os.path.join(OUT, 'mom.json'), 'w'))
    print('mom frames', n); return b64, data

def ase(a):
    r = subprocess.run([ASEPRITE, '-b'] + a, capture_output=True, text=True, timeout=600)
    if r.returncode != 0 or 'error' in (r.stdout + r.stderr).lower(): raise RuntimeError(r.stdout + r.stderr)
    return r.stdout

def b64png(path):
    return base64.b64encode(open(path, 'rb').read()).decode()

def build_bg():
    ap, mp = os.path.join(OUT, 'intro_bg.aseprite'), os.path.join(OUT, 'intro_bg_meta.json')
    print(ase(['--script-param', 'out=' + fw(ap), '--script-param', 'meta=' + fw(mp), '--script-param', 'lib=' + fw(os.path.join(ROOT, 'tools', 'ase', 'bglib.lua')),
               '--script', os.path.join(ROOT, 'tools', 'ase', 'intro_bg.lua')]).strip())
    res = {}
    for n in ('back', 'glow'):
        png = os.path.join(OUT, 'bg_%s.png' % n); ase([ap, '--layer', n, '--save-as', png]); res[n] = b64png(png)
    cp = os.path.join(OUT, 'intro_cart.aseprite'); cpng = os.path.join(OUT, 'cart.png')
    ase(['--script-param', 'out=' + fw(cp), '--script-param', 'lib=' + fw(os.path.join(ROOT, 'tools', 'ase', 'bglib.lua')), '--script', os.path.join(ROOT, 'tools', 'ase', 'intro_cart.lua')])
    ase([cp, '--save-as', cpng]); res['cart'] = b64png(cpng)
    return res, json.load(open(mp))

if __name__ == '__main__':
    mom = build_mom(); bg, bgmeta = build_bg()
    open(os.path.join(ROOT, 'js', 'introArt.js'), 'w').write(
        "// generated by tools/make_intro.py (art: assets/intro/*.aseprite, tools/ase/intro_bg.lua) - do not edit\n"
        "const INTRO_SHEETS = { mom: { img: 'data:image/png;base64,%s', json: %s } };\n"
        "const INTRO_BG = { meta: %s, back: 'data:image/png;base64,%s', glow: 'data:image/png;base64,%s', cart: 'data:image/png;base64,%s' };\n"
        % (mom[0], json.dumps(mom[1]), json.dumps(bgmeta), bg['back'], bg['glow'], bg['cart']))
    print('js/introArt.js written')
